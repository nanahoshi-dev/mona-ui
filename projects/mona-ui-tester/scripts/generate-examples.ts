import { existsSync, readdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { docsPageSlug, flattenDocsPages } from "../src/app/layout/docs-manifest";
import { readExampleComponent } from "../src/app/layout/example-project";

/**
 * Writes the registry of `src/app/examples`, and checks that each example can stand alone, since each one also has to
 * work as its own project in StackBlitz. An example is a folder, `<page>/<name>`, holding `<name>-example.component.ts`
 * and whatever it needs beside it. A guide shows one with a fenced block whose language is `example`.
 */

const REGISTRY_FILE = "examples.generated.ts";
const ALLOWED_IMPORTS = /^(@angular\/|@lucide\/angular$|@nanahoshi\/mona-ui\/|rxjs(\/|$)|\.\/[^/]+$)/;
const REFERENCE = /^```example\r?\n([^\r\n]+)\r?\n```/gm;

export interface ExampleDescription {
    readonly className: string;
    readonly files: readonly string[];
    readonly id: string;
    readonly mainFile: string;
}

/** The ways an example's main file breaks what the registry and StackBlitz rely on. */
export function checkExampleSource(id: string, source: string): string[] {
    const problems: string[] = [];
    const [page, name] = id.split("/");
    const { selector } = readExampleComponent(source);
    if (selector !== `app-${page}-${name}-example`) {
        problems.push(`${id}: the selector should be app-${page}-${name}-example, not ${selector}.`);
    }
    for (const [, specifier] of source.matchAll(/from "([^"]+)"/g)) {
        if (!ALLOWED_IMPORTS.test(specifier)) {
            problems.push(`${id}: "${specifier}" isn't available in a generated project.`);
        }
    }
    if (/\btemplate:\s*`/.test(source)) {
        problems.push(`${id}: use a template file, so the example's markup gets its own tab.`);
    }
    return problems;
}

export function findExampleReferences(markdown: string): string[] {
    return Array.from(markdown.matchAll(REFERENCE), match => match[1].trim());
}

export function renderRegistry(examples: readonly ExampleDescription[]): string {
    const entries = [...examples]
        .sort((first, second) => first.id.localeCompare(second.id))
        .map(example => {
            const modulePath = `./${example.id}/${example.mainFile.replace(/\.ts$/, "")}`;
            return [
                `    "${example.id}": {`,
                `        files: [${example.files.map(file => `"${file}"`).join(", ")}],`,
                `        load: () => import("${modulePath}").then(module => module.${example.className}),`,
                `        mainFile: "${example.mainFile}"`,
                "    }"
            ].join("\n");
        });
    return [
        "// Generated by npm run generate:examples from the folders beside this file. Do not edit.",
        'import type { Type } from "@angular/core";',
        "",
        "/* eslint-disable @typescript-eslint/naming-convention -- The keys are the examples' ids. */",
        "",
        "export interface ExampleEntry {",
        "    readonly files: readonly string[];",
        "    readonly load: () => Promise<Type<unknown>>;",
        "    readonly mainFile: string;",
        "}",
        "",
        "export const EXAMPLES: Readonly<Record<string, ExampleEntry>> = {",
        entries.join(",\n"),
        "};",
        ""
    ].join("\n");
}

function readExamples(examplesRoot: string, pages: ReadonlySet<string>): { examples: ExampleDescription[]; problems: string[] } {
    const examples: ExampleDescription[] = [];
    const problems: string[] = [];
    for (const page of readdirSync(examplesRoot, { withFileTypes: true }).filter(entry => entry.isDirectory())) {
        if (!pages.has(page.name)) {
            problems.push(`${page.name}: there's no page with this path in the manifest.`);
        }
        for (const name of readdirSync(join(examplesRoot, page.name))) {
            const id = `${page.name}/${name}`;
            const mainFile = `${name}-example.component.ts`;
            const mainPath = join(examplesRoot, page.name, name, mainFile);
            if (!existsSync(mainPath)) {
                problems.push(`${id}: it has no ${mainFile}.`);
                continue;
            }
            const source = readFileSync(mainPath, "utf8");
            problems.push(...checkExampleSource(id, source));
            examples.push({
                className: readExampleComponent(source).className,
                files: [
                    mainFile,
                    ...readdirSync(join(examplesRoot, page.name, name)).filter(file => file !== mainFile).sort()
                ],
                id,
                mainFile
            });
        }
    }
    return { examples, problems };
}

/** Every example is shown once, and every block in a guide names an example that exists. */
function checkReferences(examples: readonly ExampleDescription[], docsRoot: string): string[] {
    const problems: string[] = [];
    const counts = new Map(examples.map(example => [example.id, 0]));
    for (const page of readdirSync(docsRoot)) {
        const guide = join(docsRoot, page, "guide.md");
        if (!existsSync(guide)) {
            continue;
        }
        for (const id of findExampleReferences(readFileSync(guide, "utf8"))) {
            if (counts.has(id)) {
                counts.set(id, (counts.get(id) ?? 0) + 1);
            } else {
                problems.push(`${page}/guide.md shows "${id}", which doesn't exist.`);
            }
        }
    }
    for (const [id, count] of counts) {
        if (count !== 1) {
            problems.push(`${id}: guides show it ${count} times, and it should be once.`);
        }
    }
    return problems;
}

function main(): void {
    const testerRoot = resolve(dirname(fileURLToPath(import.meta.url)), "..");
    const examplesRoot = join(testerRoot, "src/app/examples");
    const pages = new Set(flattenDocsPages().map(docsPageSlug));
    const { examples, problems } = readExamples(examplesRoot, pages);
    problems.push(...checkReferences(examples, join(testerRoot, "src/assets/docs")));
    if (problems.length > 0) {
        console.error(problems.join("\n"));
        process.exit(1);
    }
    const registryPath = join(examplesRoot, REGISTRY_FILE);
    const registry = renderRegistry(examples);
    if (process.argv.includes("--check")) {
        const current = existsSync(registryPath) ? readFileSync(registryPath, "utf8").replace(/\r\n/g, "\n") : "";
        if (current !== registry) {
            console.error("The examples' registry is out of date. Run npm run generate:examples.");
            process.exit(1);
        }
        console.log(`${examples.length} examples are in order.`);
        return;
    }
    writeFileSync(registryPath, registry);
    console.log(`Wrote ${examples.length} examples to ${REGISTRY_FILE}.`);
}

if (process.env["VITEST"] !== "true" && process.argv[1]?.endsWith("generate-examples.ts")) {
    main();
}
