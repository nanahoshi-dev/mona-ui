/**
 * Writes the API reference from what each entry point exports.
 *
 * By default it writes the `## API` section of every component page to `src/assets/docs/<page>/api.md`, which
 * hand-written guidance in `guide.md` sits next to. `--check` fails when one of those is out of date, and `--report`
 * lists what the reference can't describe yet.
 *
 * `--data` writes what the site shows to `dist/docs-api` instead, which the tester's build serves at `/assets/api`: an
 * `index.json` and a file per entry point for the `/api` pages, and a file per component page in `pages`, for its API
 * section.
 */

const GENERATED_NOTICE = "<!-- Generated by npm run generate:api-docs from the library's JSDoc. Do not edit. -->";

export interface ApiEntry {
    readonly entryPoint: string;
    readonly symbol: ApiSymbol;
}

/** Where to find an exported name: its entry point, and the page documenting it if there is one. */
export type ApiIndex = ReadonlyMap<
    string,
    { readonly entryPoint: string; readonly page?: string; readonly symbol: ApiSymbol }
>;

export interface RenderedPage {
    readonly markdown: string;
    /** Type names the page's members use that no entry point exports. */
    readonly unexported: readonly string[];
}

/** What a page's API section lists, and the type names its members use that no entry point exports. */
export interface PageApi {
    readonly page: ApiPageReference;
    readonly unexported: readonly string[];
}

/** What the `/api` pages load: the index, and each entry point's symbols. */
export interface ApiReference {
    readonly entryPoints: readonly ApiEntryPointReference[];
    readonly index: ApiReferenceIndex;
}

/** The parts of a symbol whose text names other types. */
type TypedParts = Pick<
    ApiSymbol,
    "extends" | "inputs" | "methods" | "outputs" | "properties" | "signature" | "templateContext"
>;

function escapeCell(text: string): string {
    return text
        .replace(/\s*\r?\n\s*/g, " ")
        .replace(/\\?\|/g, "\\|")
        .trim();
}

/** A code span for a table cell, using a longer fence when the text itself holds a backtick. */
function code(text: string): string {
    const fence = text.includes("`") ? "``" : "`";
    return `${fence}${escapeCell(text)}${fence}`;
}

/** A link to a symbol's reference page, with its name as code. */
function symbolLink(name: string, entryPoint: string): string {
    return `[\`${name}\`](${apiSymbolPath(entryPoint, name)})`;
}

function table(headers: readonly string[], rows: readonly (readonly string[])[]): string {
    return [
        `| ${headers.join(" | ")} |`,
        `| ${headers.map(() => "---").join(" | ")} |`,
        ...rows.map(row => `| ${row.join(" | ")} |`)
    ].join("\n");
}

function memberName(member: ApiMember): string {
    const flags = [member.required ? "required" : "", member.twoWay ? "two-way" : ""].filter(Boolean);
    const name = code(member.alias ?? member.name);
    return flags.length > 0 ? `${name} (${flags.join(", ")})` : name;
}

function inputsTable(inputs: readonly ApiMember[]): string {
    return table(
        ["Name", "Type", "Default", "Description"],
        inputs.map(input => [
            memberName(input),
            code(input.type),
            input.defaultValue === undefined ? "—" : code(input.defaultValue),
            escapeCell(prose(input.description))
        ])
    );
}

/** An output table, with the change event each `model()` adds, since that's what a one-way listener binds. */
function outputsTable(outputs: readonly ApiMember[], inputs: readonly ApiMember[]): string {
    return table(
        ["Name", "Type", "Description"],
        withModelEvents(outputs, inputs).map(output => [
            code(output.alias ?? output.name),
            code(output.type),
            escapeCell(prose(output.description))
        ])
    );
}

function methodsTable(methods: readonly ApiMethod[]): string {
    const hasDescriptions = methods.some(method => method.description);
    return table(
        hasDescriptions ? ["Signature", "Description"] : ["Signature"],
        methods.map(method =>
            hasDescriptions ? [code(method.signature), escapeCell(prose(method.description))] : [code(method.signature)]
        )
    );
}

function propertyName(member: ApiMember): string {
    const name = code(`${member.name}${member.optional ? "?" : ""}`);
    return member.readonly ? `${name} (read-only)` : name;
}

function propertiesTable(properties: readonly ApiMember[]): string {
    const hasDescriptions = properties.some(property => property.description);
    return table(
        hasDescriptions ? ["Name", "Type", "Description"] : ["Name", "Type"],
        properties.map(property => {
            const cells = [propertyName(property), code(property.type)];
            return hasDescriptions ? [...cells, escapeCell(prose(property.description))] : cells;
        })
    );
}

/**
 * A table of exports, each linking to its reference page, with the first sentence of what it is. A description column
 * nothing fills is left out.
 */
function exportsTable(heading: string, exports: readonly ApiPageExport[]): string {
    const hasDescriptions = exports.some(item => item.summary);
    return table(
        hasDescriptions ? [heading, "Kind", "Description"] : [heading, "Kind"],
        exports.map(item => {
            const cells = [symbolLink(item.name, item.entryPoint), KIND_LABELS[item.kind]];
            return hasDescriptions ? [...cells, escapeCell(item.summary)] : cells;
        })
    );
}

/** A table of exports for each entry point they come from: the page's own first, then each other one, named above it. */
function exportsTables(heading: string, exports: readonly ApiPageExport[], entryPoints: readonly string[]): string[] {
    return entryPoints.flatMap((entryPoint, position) => {
        const own = exports.filter(item => item.entryPoint === entryPoint);
        if (own.length === 0) {
            return [];
        }
        const rows = exportsTable(heading, own);
        return position === 0 ? [rows] : [`From ${code(`${PACKAGE_NAME}/${entryPoint}`)}:`, rows];
    });
}

/** The short facts under a symbol's heading: its selector, and how it relates to other types. */
function symbolFacts(symbol: ApiSymbol): string[] {
    const facts: string[] = [];
    if (symbol.selector) {
        facts.push(`**Selector:** ${code(symbol.selector)}`);
    }
    if (symbol.pipeName) {
        facts.push(`**Pipe:** ${code(symbol.pipeName)}`);
    }
    if (symbol.exportAs) {
        facts.push(`**Exported as:** ${code(symbol.exportAs)}`);
    }
    if (symbol.typeParameters?.length) {
        facts.push(`**Type parameters:** ${symbol.typeParameters.map(code).join(", ")}`);
    }
    if (symbol.extends?.length) {
        facts.push(`**Extends:** ${symbol.extends.map(code).join(", ")}`);
    }
    if (symbol.implements?.length) {
        facts.push(`**Implements:** ${symbol.implements.map(code).join(", ")}`);
    }
    return facts;
}

/** The body of one symbol. `depth` is the heading level of its parts, or `null` to label them in bold. */
function renderSymbolBody(symbol: ApiSymbol, depth: number | null): string[] {
    const label = (text: string): string => (depth === null ? `**${text}**` : `${"#".repeat(depth)} ${text}`);
    const blocks: string[] = [];
    const description = prose(symbol.description);
    if (description) {
        blocks.push(description);
    }
    const facts = symbolFacts(symbol);
    if (facts.length > 0) {
        blocks.push(facts.join("  \n"));
    }
    if (symbol.signature) {
        blocks.push(`\`\`\`typescript\n${symbol.signature}\n\`\`\``);
    }
    const inputs = symbol.inputs ?? [];
    if (inputs.length > 0) {
        blocks.push(label("Inputs"), inputsTable(inputs));
    }
    if ((symbol.outputs?.length ?? 0) > 0 || inputs.some(input => input.twoWay)) {
        blocks.push(label("Outputs"), outputsTable(symbol.outputs ?? [], inputs));
    }
    if (symbol.templateContext && symbol.templateContext.members.length > 0) {
        blocks.push(label("Template context"), propertiesTable(symbol.templateContext.members));
    }
    if ((symbol.properties?.length ?? 0) > 0) {
        blocks.push(depth === null ? propertiesTable(symbol.properties ?? []) : label("Properties"));
        if (depth !== null) {
            blocks.push(propertiesTable(symbol.properties ?? []));
        }
    }
    if ((symbol.methods?.length ?? 0) > 0) {
        blocks.push(label("Methods"), methodsTable(symbol.methods ?? []));
    }
    if ((symbol.enumMembers?.length ?? 0) > 0) {
        blocks.push(
            table(
                ["Member", "Value", "Description"],
                (symbol.enumMembers ?? []).map(member => [
                    code(member.name),
                    code(member.value),
                    escapeCell(prose(member.description))
                ])
            )
        );
    }
    return blocks;
}

function memberCount(symbol: ApiSymbol): number {
    return (symbol.inputs?.length ?? 0) + (symbol.outputs?.length ?? 0) + (symbol.methods?.length ?? 0);
}

/** Orders symbols by kind, and within a kind puts the largest first, which is the page's main component. */
export function sortSymbols(symbols: readonly ApiSymbol[]): ApiSymbol[] {
    return [...symbols].sort(
        (first, second) =>
            KIND_ORDER.indexOf(first.kind) - KIND_ORDER.indexOf(second.kind) ||
            memberCount(second) - memberCount(first) ||
            first.name.localeCompare(second.name, "en")
    );
}

function typeTexts(symbol: Partial<TypedParts>): string[] {
    const members = [
        ...(symbol.inputs ?? []),
        ...(symbol.outputs ?? []),
        ...(symbol.properties ?? []),
        ...(symbol.templateContext?.members ?? [])
    ];
    return [
        ...members.map(member => member.type),
        ...(symbol.methods ?? []).map(method => method.signature),
        ...(symbol.extends ?? []),
        symbol.signature ?? ""
    ];
}

function referencedNames(symbol: Partial<TypedParts>): Set<string> {
    return new Set(typeTexts(symbol).flatMap(mentionedNames));
}

/** A generic parameter's name, such as `T` or `TData`, which no entry point could export. */
function isUtilityName(name: string): boolean {
    return /^[A-Z]$|^T[A-Z]\w*$/.test(name);
}

/**
 * Finds the types a page's members use from elsewhere: those documented on another page, and those whose entry point
 * has no page, along with what those use in turn.
 */
function resolveRelated(
    symbols: readonly ApiSymbol[],
    index: ApiIndex
): {
    readonly related: readonly ApiEntry[];
    readonly unexported: readonly string[];
} {
    const local = new Set(symbols.map(symbol => symbol.name));
    const related = new Map<string, ApiEntry>();
    const unexported = new Set<string>();
    const pending = [...symbols];

    while (pending.length > 0) {
        const symbol = pending.pop();
        if (!symbol) {
            break;
        }
        const generics = new Set((symbol.typeParameters ?? []).map(parameter => parameter.split(/\s/)[0]));
        for (const name of referencedNames(symbol)) {
            if (local.has(name) || generics.has(name) || related.has(name) || isUtilityName(name)) {
                continue;
            }
            const found = index.get(name);
            if (!found) {
                unexported.add(name);
                continue;
            }
            related.set(name, { entryPoint: found.entryPoint, symbol: found.symbol });
            if (!found.page) {
                pending.push(found.symbol);
            }
        }
    }
    return {
        related: [...related.values()].sort((first, second) =>
            first.symbol.name.localeCompare(second.symbol.name, "en")
        ),
        unexported: [...unexported].sort((first, second) => first.localeCompare(second, "en"))
    };
}

/**
 * What one page's API section lists: its exports by kind, with what a template uses each by and the first sentence of
 * what it is, the types they use from elsewhere, and the exported names those sentences mention.
 */
export function buildApiPage(entries: readonly ApiEntry[], index: ApiIndex): PageApi {
    const symbols = entries.map(entry => entry.symbol);
    const entryOf = new Map(entries.map(entry => [entry.symbol.name, entry.entryPoint]));
    const { related, unexported } = resolveRelated(symbols, index);
    const exports = sortSymbols(symbols).map(
        (symbol): ApiPageExport => ({
            entryPoint: entryOf.get(symbol.name) ?? "",
            kind: symbol.kind,
            name: symbol.name,
            ...(symbol.pipeName ? { pipeName: symbol.pipeName } : {}),
            ...(symbol.selector ? { selector: symbol.selector } : {}),
            summary: summarize(symbol.description)
        })
    );
    const links: Record<string, string> = {};
    for (const { summary } of exports) {
        for (const [, name] of summary.matchAll(/`([A-Z]\w*)`/g)) {
            const entryPoint = entryOf.get(name) ?? index.get(name)?.entryPoint;
            if (entryPoint) {
                links[name] = entryPoint;
            }
        }
    }
    return {
        page: {
            entryPoints: [...new Set(entries.map(entry => entry.entryPoint))],
            exports,
            links,
            related: related.map(({ entryPoint, symbol }) => ({ entryPoint, name: symbol.name }))
        },
        unexported
    };
}

/**
 * Renders one page's API section: a table of what the page documents, and one of its types, each export linking to
 * its reference page, which describes it in full. The site shows the same section from `buildApiPage()`.
 */
export function renderApiPage(entries: readonly ApiEntry[], index: ApiIndex): RenderedPage {
    const { page, unexported } = buildApiPage(entries, index);
    const { entryPoints, related } = page;
    const blocks: string[] = [GENERATED_NOTICE, "## API"];

    if (entryPoints.length > 0) {
        blocks.push(
            `Everything below is imported from ${code(`${PACKAGE_NAME}/${entryPoints[0]}`)}` +
                `${entryPoints.length > 1 ? ", unless a table names another entry point" : ""}. ` +
                "Each name links to its reference page, with every input, output, property and method."
        );
    }

    blocks.push(
        ...exportsTables(
            "Name",
            page.exports.filter(item => !TYPE_KINDS.has(item.kind)),
            entryPoints
        )
    );

    const types = page.exports.filter(item => TYPE_KINDS.has(item.kind));
    if (types.length > 0 || related.length > 0) {
        blocks.push("### Types", ...exportsTables("Type", types, entryPoints));
        if (related.length > 0) {
            const links = related.map(({ entryPoint, name }) => symbolLink(name, entryPoint));
            blocks.push(`**Related types:** ${links.join(", ")}`);
        }
    }
    return { markdown: `${blocks.join("\n\n")}\n`, unexported };
}

/**
 * The entry points and exported names a page documents, from its manifest entry. A page without `apiExports` takes
 * what the other pages of its entry point don't name, so an export is never left off every page.
 */
export function selectPageEntries(
    page: DocsPage,
    symbolsByEntry: ReadonlyMap<string, readonly ApiSymbol[]>,
    allPages: readonly DocsPage[] = []
): ApiEntry[] {
    if (!page.entryPoint) {
        return [];
    }
    const namedElsewhere = new Set(
        allPages
            .filter(other => other !== page && other.entryPoint === page.entryPoint)
            .flatMap(other => other.apiExports ?? [])
    );
    const own = (symbolsByEntry.get(page.entryPoint) ?? [])
        .filter(symbol =>
            page.apiExports ? page.apiExports.includes(symbol.name) : !namedElsewhere.has(symbol.name)
        )
        .map((symbol): ApiEntry => ({ entryPoint: page.entryPoint ?? "", symbol }));
    const taken = new Set(own.map(entry => entry.symbol.name));
    const also = (page.apiAlsoFrom ?? []).flatMap(entryPoint =>
        (symbolsByEntry.get(entryPoint) ?? [])
            .filter(symbol => !taken.has(symbol.name))
            .map((symbol): ApiEntry => ({ entryPoint, symbol }))
    );
    return [...own, ...also];
}

/** The members a symbol takes from its exported base types, nearest first, following each base's own bases. */
function inheritance(symbol: ApiSymbol, index: ApiIndex): ApiInheritance[] {
    const found: ApiInheritance[] = [];
    const seen = new Set([symbol.name]);
    const pending = [...(symbol.extends ?? [])];
    while (pending.length > 0) {
        const name = /^[A-Za-z_$][\w$]*/.exec(pending.shift()?.trim() ?? "")?.[0];
        const base = name && !seen.has(name) ? index.get(name)?.symbol : undefined;
        if (!name || !base) {
            continue;
        }
        seen.add(name);
        if (memberCount(base) + (base.properties?.length ?? 0) > 0) {
            found.push({
                from: name,
                inputs: base.inputs,
                methods: base.methods,
                outputs: base.outputs,
                properties: base.properties
            });
        }
        pending.push(...(base.extends ?? []));
    }
    return found;
}

/** Every description a symbol's page shows, to find the names its code spans mention. */
function descriptions(symbol: ApiSymbolReference): string[] {
    const members = [
        ...(symbol.inputs ?? []),
        ...(symbol.outputs ?? []),
        ...(symbol.properties ?? []),
        ...(symbol.methods ?? []),
        ...(symbol.enumMembers ?? []),
        ...(symbol.templateContext?.members ?? []),
        ...(symbol.inherited ?? []).flatMap(base => [
            ...(base.inputs ?? []),
            ...(base.outputs ?? []),
            ...(base.properties ?? []),
            ...(base.methods ?? [])
        ])
    ];
    return [symbol.description, ...members.map(member => member.description)];
}

/** The exported names a symbol's page can link: those its types, base types and descriptions mention. */
function linkableNames(symbol: ApiSymbolReference): Set<string> {
    const inCode = descriptions(symbol).flatMap(text =>
        Array.from(prose(text).matchAll(/`([A-Z]\w*)`/g), match => match[1])
    );
    return new Set([
        symbol.name,
        ...referencedNames(symbol),
        ...(symbol.inherited ?? []).flatMap(base => [base.from, ...referencedNames(base)]),
        ...(symbol.usedBy ?? []),
        ...inCode
    ]);
}

/** What the `/api` pages show, for every entry point. */
export function buildApiReference(
    symbolsByEntry: ReadonlyMap<string, readonly ApiSymbol[]>,
    index: ApiIndex,
    pages: readonly DocsPage[]
): ApiReference {
    const guides = new Map(pages.map(page => [page.path, { path: page.path, title: page.title }]));
    // Keyed by entry point too: a few names are exported by more than one, not always for the same declaration.
    const pageOf = new Map<string, string>();
    for (const page of pages) {
        for (const { entryPoint, symbol } of selectPageEntries(page, symbolsByEntry, pages)) {
            if (!pageOf.has(`${entryPoint}/${symbol.name}`)) {
                pageOf.set(`${entryPoint}/${symbol.name}`, page.path);
            }
        }
    }
    const usedBy = new Map<string, Set<string>>();
    for (const symbols of symbolsByEntry.values()) {
        for (const symbol of symbols) {
            for (const name of referencedNames(symbol)) {
                if (name !== symbol.name && index.has(name)) {
                    usedBy.set(name, (usedBy.get(name) ?? new Set()).add(symbol.name));
                }
            }
        }
    }

    const entryPoints = [...symbolsByEntry]
        .filter(([, symbols]) => symbols.length > 0)
        .sort(([first], [second]) => first.localeCompare(second, "en"))
        .map(([name, symbols]): ApiEntryPointReference => {
            const own = new Set(symbols.map(symbol => symbol.name));
            const references = sortSymbols(symbols).map((symbol): ApiSymbolReference => {
                const inherited = inheritance(symbol, index);
                const page = pageOf.get(`${name}/${symbol.name}`);
                const users = [...(usedBy.get(symbol.name) ?? [])].sort((first, second) =>
                    first.localeCompare(second, "en")
                );
                return {
                    ...symbol,
                    ...(inherited.length > 0 ? { inherited } : {}),
                    ...(page && guides.has(page) ? { page: guides.get(page) } : {}),
                    ...(users.length > 0 ? { usedBy: users } : {})
                };
            });
            // A name this entry point exports means its own, where another entry point exports one by that name too.
            const links: Record<string, string> = {};
            for (const linked of [...new Set(references.flatMap(symbol => [...linkableNames(symbol)]))].sort()) {
                const entryPoint = own.has(linked) ? name : index.get(linked)?.entryPoint;
                if (entryPoint) {
                    links[linked] = entryPoint;
                }
            }
            const entryPages: ApiGuidePage[] = pages
                .filter(page => page.entryPoint === name || page.apiAlsoFrom?.includes(name))
                .map(page => ({ path: page.path, title: page.title }));
            return { links, name, pages: entryPages, symbols: references };
        });

    return {
        entryPoints,
        index: {
            entryPoints: entryPoints.map(entryPoint => ({
                name: entryPoint.name,
                pages: entryPoint.pages,
                symbols: entryPoint.symbols.map(symbol => ({
                    kind: symbol.kind,
                    name: symbol.name,
                    summary: summarize(symbol.description)
                }))
            }))
        }
    };
}

/**
 * One entry point's whole reference as markdown, for coding agents, which read files rather than the `/api` pages.
 * Links are site paths, which `generate-ai-docs.ts` points at its files.
 */
export function renderApiReference(entryPoint: ApiEntryPointReference): string {
    const importPath = `${PACKAGE_NAME}/${entryPoint.name}`;
    const blocks: string[] = [`# \`${importPath}\``, `Everything \`${importPath}\` exports.`];
    if (entryPoint.pages.length > 0) {
        const guides = entryPoint.pages.map(page => `[${page.title}](/components/${page.path})`);
        blocks.push(`**Guides:** ${guides.join(", ")}`);
    }
    for (const symbol of entryPoint.symbols) {
        blocks.push(`## \`${symbol.name}\``, `${KIND_LABELS[symbol.kind]}.`, ...renderSymbolBody(symbol, 3));
        for (const base of symbol.inherited ?? []) {
            blocks.push(
                `### Inherited from \`${base.from}\``,
                ...renderSymbolBody({ ...base, description: "", kind: "class", name: base.from }, null)
            );
        }
        if (symbol.usedBy?.length) {
            const users = symbol.usedBy.map(name =>
                entryPoint.links[name] ? symbolLink(name, entryPoint.links[name]) : code(name)
            );
            blocks.push(`**Used by:** ${users.join(", ")}`);
        }
    }
    return `${blocks.join("\n\n")}\n`;
}

/** Reads every entry point's exports, and which component page documents each one. */
function readLibrary(libraryDirectory: string): {
    readonly declared: ReadonlySet<string>;
    readonly index: ApiIndex;
    readonly pages: readonly DocsPage[];
    readonly symbolsByEntry: ReadonlyMap<string, readonly ApiSymbol[]>;
} {
    const project = createLibraryProject(libraryDirectory);
    const entryPoints = readdirSync(libraryDirectory, { withFileTypes: true })
        .filter(item => item.isDirectory() && item.name !== "internal")
        .map(item => item.name)
        .filter(name => existsSync(join(libraryDirectory, name, "public-api.ts")))
        .sort((first, second) => first.localeCompare(second, "en"));
    const sources = new Map(
        entryPoints.map(name => {
            const file = `${libraryDirectory}/${name}/public-api.ts`;
            return [name, project.getSourceFile(file) ?? project.addSourceFileAtPath(file)];
        })
    );

    const publicClasses = new Set<ClassDeclaration>();
    for (const source of sources.values()) {
        for (const declarations of source.getExportedDeclarations().values()) {
            declarations.filter(item => item instanceof ClassDeclaration).forEach(item => publicClasses.add(item));
        }
    }
    const symbolsByEntry = new Map(
        [...sources].map(([name, source]) => [name, readEntryPoint(source, item => publicClasses.has(item))] as const)
    );

    const pages = flattenDocsPages().filter(page => page.kind === "component");
    const pageOfSymbol = new Map<string, string>();
    for (const page of pages) {
        for (const { symbol } of selectPageEntries(page, symbolsByEntry, pages)) {
            if (!pageOfSymbol.has(symbol.name)) {
                pageOfSymbol.set(symbol.name, page.path);
            }
        }
    }
    const index = new Map<string, { entryPoint: string; page?: string; symbol: ApiSymbol }>();
    for (const [entryPoint, symbols] of symbolsByEntry) {
        for (const symbol of symbols) {
            const page = pageOfSymbol.get(symbol.name);
            const known = index.get(symbol.name);
            if (!known || (page && !known.page)) {
                index.set(symbol.name, { entryPoint, page, symbol });
            }
        }
    }

    const declared = new Set(
        project
            .getSourceFiles()
            .filter(file => !file.getFilePath().endsWith(".spec.ts"))
            .flatMap(file => [
                ...file.getClasses(),
                ...file.getInterfaces(),
                ...file.getTypeAliases(),
                ...file.getEnums()
            ])
            .map(declaration => declaration.getName() ?? "")
    );
    return { declared, index, pages, symbolsByEntry };
}

function writeApiData(
    outputDirectory: string,
    reference: ApiReference,
    pages: ReadonlyMap<string, ApiPageReference>
): void {
    rmSync(outputDirectory, { force: true, recursive: true });
    mkdirSync(join(outputDirectory, "pages"), { recursive: true });
    writeFileSync(join(outputDirectory, "index.json"), JSON.stringify(reference.index));
    for (const entryPoint of reference.entryPoints) {
        writeFileSync(join(outputDirectory, `${entryPoint.name}.json`), JSON.stringify(entryPoint));
    }
    for (const [slug, page] of pages) {
        writeFileSync(join(outputDirectory, "pages", `${slug}.json`), JSON.stringify(page));
    }
}

function main(): void {
    const scriptDirectory = dirname(fileURLToPath(import.meta.url));
    const docsDirectory = resolve(scriptDirectory, "../src/assets/docs");
    const libraryDirectory = resolve(scriptDirectory, "../../mona-ui").replaceAll("\\", "/");
    const check = process.argv.includes("--check");
    const report = process.argv.includes("--report");
    const { declared, index, pages, symbolsByEntry } = readLibrary(libraryDirectory);

    if (process.argv.includes("--data")) {
        const reference = buildApiReference(symbolsByEntry, index, pages);
        const pageApis = new Map(
            pages.map(page => [docsPageSlug(page), buildApiPage(selectPageEntries(page, symbolsByEntry, pages), index).page])
        );
        writeApiData(resolve(scriptDirectory, "../../../dist/docs-api"), reference, pageApis);
        const symbolCount = reference.entryPoints.reduce((total, entry) => total + entry.symbols.length, 0);
        console.log(
            `Wrote the reference of ${symbolCount} exports from ${reference.entryPoints.length} entry points, ` +
                `and the API sections of ${pageApis.size} pages, to dist/docs-api.`
        );
        return;
    }

    const stale: string[] = [];
    const unexported = new Map<string, Set<string>>();
    for (const page of pages) {
        const rendered = renderApiPage(selectPageEntries(page, symbolsByEntry, pages), index);
        rendered.unexported
            .filter(name => declared.has(name) && !/Variant/.test(name))
            .forEach(name => unexported.set(name, (unexported.get(name) ?? new Set()).add(page.path)));

        const file = join(docsDirectory, docsPageSlug(page), "api.md");
        const current = existsSync(file) ? readFileSync(file, "utf8").replace(/\r\n/g, "\n") : null;
        if (current === rendered.markdown) {
            continue;
        }
        stale.push(page.path);
        if (!check) {
            mkdirSync(dirname(file), { recursive: true });
            writeFileSync(file, rendered.markdown);
        }
    }

    if (report) {
        console.log(`\nTypes used in the public API that no entry point exports (${unexported.size}):`);
        [...unexported]
            .sort(([first], [second]) => first.localeCompare(second, "en"))
            .forEach(([name, where]) => console.log(`  ${name}: ${[...where].join(", ")}`));
    }
    if (check && stale.length > 0) {
        console.error(`API docs are out of date for: ${stale.join(", ")}. Run npm run generate:api-docs.`);
    }
    if (check && unexported.size > 0) {
        console.error(`The public API uses types no entry point exports: ${[...unexported.keys()].join(", ")}.`);
    }
    if (check && (stale.length > 0 || unexported.size > 0)) {
        process.exit(1);
    }
    console.log(
        check
            ? `API docs are up to date for ${pages.length} pages.`
            : `Updated ${stale.length} of ${pages.length} API pages.`
    );
}

if (process.env["VITEST"] !== "true" && process.argv[1]?.endsWith("generate-api-docs.ts")) {
    main();
}
