import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import prettier from "prettier";
import { Node, Project, type ParameterDeclaration, type TypeNode } from "ts-morph";

const scriptDir = path.dirname(fileURLToPath(import.meta.url));

export const MESSAGES_MODEL_FILE = path.resolve(scriptDir, "../projects/mona-ui/i18n/models/mona-locale-messages.ts");
export const MESSAGE_PARAMETERS_FILE = path.resolve(scriptDir, "../projects/mona-ui/i18n/icu/message-parameters.ts");

export interface MessageParameterInfo {
    readonly name: string;
    readonly optional: boolean;
    readonly type: "number" | "string";
}

/** Parameters of each message by namespace and key; `null` for a plain string message. */
export type MessageParameterTable = ReadonlyMap<string, ReadonlyMap<string, readonly MessageParameterInfo[] | null>>;

/**
 * Reads `MonaLocaleMessages` and every namespace interface it references, and lists each message's parameters in
 * declaration order. Namespaces and keys are sorted, so the table does not change when members are reordered.
 */
export function readMessageParameterTable(modelFile: string = MESSAGES_MODEL_FILE): MessageParameterTable {
    const project = new Project({ skipAddingFilesFromTsConfig: true });
    const modelSource = project.addSourceFileAtPath(modelFile);
    const root = modelSource.getInterfaceOrThrow("MonaLocaleMessages");
    const table = new Map<string, Map<string, readonly MessageParameterInfo[] | null>>();

    for (const namespaceProperty of [...root.getProperties()].sort(byName)) {
        const namespace = namespaceProperty.getName();
        const typeName = namespaceProperty.getTypeNodeOrThrow().getText();
        const importDeclaration = modelSource
            .getImportDeclarations()
            .find(d => d.getNamedImports().some(n => n.getName() === typeName));
        if (importDeclaration == null) {
            throw new Error(`Cannot find the import of "${typeName}" for namespace "${namespace}"`);
        }
        const namespaceFile = path.resolve(
            path.dirname(modelFile),
            `${importDeclaration.getModuleSpecifierValue()}.ts`
        );
        const namespaceInterface = project.addSourceFileAtPath(namespaceFile).getInterfaceOrThrow(typeName);

        const messages = new Map<string, readonly MessageParameterInfo[] | null>();
        const members = [...namespaceInterface.getProperties(), ...namespaceInterface.getMethods()].sort(byName);
        for (const member of members) {
            const key = member.getName();
            const where = `${namespace}.${key}`;
            if (Node.isMethodSignature(member)) {
                messages.set(key, readParameters(member.getParameters(), member.getReturnTypeNodeOrThrow(), where));
                continue;
            }
            const typeNode = member.getTypeNodeOrThrow();
            if (Node.isFunctionTypeNode(typeNode)) {
                messages.set(key, readParameters(typeNode.getParameters(), typeNode.getReturnTypeNodeOrThrow(), where));
            } else if (typeNode.getText() === "string") {
                messages.set(key, null);
            } else {
                throw new Error(`Message "${where}" must be a string or a function returning a string`);
            }
        }
        table.set(namespace, messages);
    }
    return table;
}

export async function generateMessageParametersModuleContent(
    table: MessageParameterTable = readMessageParameterTable()
): Promise<string> {
    const namespaces = [...table].map(([namespace, messages]) => {
        const entries = [...messages].map(([key, parameters]) => {
            if (parameters == null) {
                return `${key}: null`;
            }
            const list = parameters.map(
                p => `{ name: "${p.name}", ${p.optional ? "optional: true, " : ""}type: "${p.type}" }`
            );
            return `${key}: [${list.join(", ")}]`;
        });
        return `${namespace}: {\n${entries.join(",\n")}\n}`;
    });
    const content = `// Generated by scripts/generate-message-parameters.ts from i18n/message-types. Do not edit.
// Run \`npm run generate:message-parameters\` after changing a message type.

import type { MonaMessageParameter } from "./models/mona-locale-data";

/**
 * The parameters of every message, by namespace and key, in the order the message function takes them. A plain
 * string message has \`null\`.
 */
export const MONA_MESSAGE_PARAMETERS: Readonly<
    Record<string, Readonly<Record<string, readonly MonaMessageParameter[] | null>>>
> = {
${namespaces.join(",\n")}
};
`;
    const options = await prettier.resolveConfig(MESSAGE_PARAMETERS_FILE);
    return prettier.format(content, { ...options, filepath: MESSAGE_PARAMETERS_FILE });
}

function byName(a: { getName(): string }, b: { getName(): string }): number {
    return a.getName() < b.getName() ? -1 : a.getName() > b.getName() ? 1 : 0;
}

function readParameters(
    parameters: readonly ParameterDeclaration[],
    returnType: TypeNode,
    where: string
): readonly MessageParameterInfo[] {
    if (returnType.getText() !== "string") {
        throw new Error(`Message "${where}" must return a string`);
    }
    return parameters.map(parameter => {
        const type = parameter.getTypeNodeOrThrow().getText();
        if (type !== "number" && type !== "string") {
            throw new Error(`Parameter "${parameter.getName()}" of message "${where}" must be a number or a string`);
        }
        return { name: parameter.getName(), optional: parameter.hasQuestionToken(), type };
    });
}

function normalizeNewlines(text: string): string {
    return text.replace(/\r\n/g, "\n");
}

async function main(): Promise<void> {
    const content = await generateMessageParametersModuleContent();
    if (process.argv.includes("--check")) {
        const existing = fs.existsSync(MESSAGE_PARAMETERS_FILE) ? fs.readFileSync(MESSAGE_PARAMETERS_FILE, "utf8") : "";
        if (normalizeNewlines(existing) !== normalizeNewlines(content)) {
            console.error(
                `${MESSAGE_PARAMETERS_FILE} is out of date. Run \`npm run generate:message-parameters\` and commit the result.`
            );
            process.exit(1);
        }
        console.log("Message parameter table is up to date.");
        return;
    }
    fs.writeFileSync(MESSAGE_PARAMETERS_FILE, content, "utf8");
    console.log(`Generated ${MESSAGE_PARAMETERS_FILE}`);
}

if (process.argv[1] && fileURLToPath(import.meta.url) === path.resolve(process.argv[1])) {
    main().catch((error: unknown) => {
        console.error(error);
        process.exit(1);
    });
}
